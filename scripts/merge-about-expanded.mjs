/**
 * Merges batch1 + batch2 expanded about pages into generated TypeScript outputs.
 * Run: node scripts/merge-about-expanded.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { batch1Pages } from "./generate-about-expanded.mjs";
import { batch2Pages } from "./about-batch2-pages.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const contentPath = join(root, "src/lib/aboutExpandedContent.ts");
const metaPath = join(root, "src/lib/aboutExpandedPages.ts");

const allPages = [...batch1Pages, ...batch2Pages];

if (allPages.length !== 70) {
  throw new Error(`Expected 70 merged pages, got ${allPages.length}`);
}

const slugs = new Set(allPages.map((p) => p.slug));
if (slugs.size !== 70) {
  throw new Error("Duplicate slugs in merged pages");
}

const batch1Slugs = new Set(batch1Pages.map((p) => p.slug));
for (const p of batch2Pages) {
  if (batch1Slugs.has(p.slug)) {
    throw new Error(`Batch2 slug collides with batch1: ${p.slug}`);
  }
}

function blockToTs(block, indent = "      ") {
  switch (block.type) {
    case "p":
      return `${indent}{ type: "p", html: ${JSON.stringify(block.html)} }`;
    case "h2":
      return `${indent}{ type: "h2", text: ${JSON.stringify(block.text)} }`;
    case "ul":
    case "ol":
      return `${indent}{ type: "${block.type}", items: ${JSON.stringify(block.items)} }`;
    case "pre":
      return `${indent}{ type: "pre", code: ${JSON.stringify(block.code)} }`;
    case "figure":
      return `${indent}{ type: "figure", illustration: ${JSON.stringify(block.illustration)}, alt: ${JSON.stringify(block.alt)}, caption: ${JSON.stringify(block.caption)} }`;
    default:
      throw new Error(`Unknown block type: ${block.type}`);
  }
}

function generateContentTs(pageList) {
  const entries = pageList
    .map((page) => {
      const blocks = page.blocks.map((b) => blockToTs(b)).join(",\n");
      return `  ${JSON.stringify(page.slug)}: [\n${blocks}\n  ]`;
    })
    .join(",\n\n");

  const slugList = pageList.map((p) => `  ${JSON.stringify(p.slug)}`).join(",\n");

  return `/** Auto-generated by scripts/merge-about-expanded.mjs — do not edit by hand. */
export type AboutContentBlock =
  | { type: "p"; html: string }
  | { type: "h2"; text: string }
  | { type: "ul"; items: string[] }
  | { type: "ol"; items: string[] }
  | { type: "pre"; code: string }
  | { type: "figure"; illustration: string; alt: string; caption: string };

export const expandedAboutContent: Record<string, AboutContentBlock[]> = {
${entries}
};

export const EXPANDED_ABOUT_SLUGS: readonly string[] = [
${slugList}
] as const;

export const expandedAboutSlugs: Set<string> = new Set(EXPANDED_ABOUT_SLUGS);

export function getExpandedAboutContent(
  slug: string,
): AboutContentBlock[] | undefined {
  return expandedAboutContent[slug];
}
`;
}

function metaEntry(p) {
  return `  {
    slug: ${JSON.stringify(p.slug)},
    parentSlug: ${JSON.stringify(p.parentSlug)},
    title: ${JSON.stringify(p.title)},
    description: ${JSON.stringify(p.description)},
    summary: ${JSON.stringify(p.summary)},
  }`;
}

function generateMetaTs(batch1Meta, batch2List) {
  const batch1Entries = batch1Meta.map(metaEntry).join(",\n");
  const batch2Entries = batch2List.map(metaEntry).join(",\n");

  return `export type ExpandedAboutPageMeta = {
  slug: string;
  parentSlug: string;
  title: string;
  description: string;
  summary: string;
};

/** Metadata for 70 expanded about guides (content lives in aboutExpandedContent.ts). */
export const expandedAboutPageMeta: ExpandedAboutPageMeta[] = [
${batch1Entries},
${batch2Entries}
];
`;
}

/** Parse existing batch1 metadata objects from aboutExpandedPages.ts */
function readBatch1Meta() {
  const src = readFileSync(metaPath, "utf8");
  const match = src.match(
    /export const expandedAboutPageMeta[^=]*=\s*\[([\s\S]*?)\n\];/,
  );
  if (!match) {
    throw new Error("Could not parse expandedAboutPageMeta from aboutExpandedPages.ts");
  }

  const entries = [];
  const objRe =
    /\{\s*slug:\s*"([^"]+)",\s*parentSlug:\s*"([^"]+)",\s*title:\s*"([^"]+)",\s*description:\s*\n?\s*"([^"]*(?:\\.[^"]*)*)",\s*summary:\s*\n?\s*"([^"]*(?:\\.[^"]*)*)",?\s*\}/gs;

  let m;
  while ((m = objRe.exec(match[1])) !== null) {
    entries.push({
      slug: m[1],
      parentSlug: m[2],
      title: m[3],
      description: m[4].replace(/\\"/g, '"'),
      summary: m[5].replace(/\\"/g, '"'),
    });
  }

  if (entries.length !== batch1Pages.length) {
    throw new Error(
      `Parsed ${entries.length} batch1 meta entries, expected ${batch1Pages.length}`,
    );
  }

  return entries;
}

const batch1Meta = readBatch1Meta();

writeFileSync(contentPath, generateContentTs(allPages), "utf8");
writeFileSync(metaPath, generateMetaTs(batch1Meta, batch2Pages), "utf8");

console.log(`Wrote ${contentPath} with ${allPages.length} expanded about pages.`);
console.log(`Wrote ${metaPath} with ${batch1Meta.length + batch2Pages.length} metadata entries.`);
console.log(`EXPANDED_ABOUT_SLUGS count: ${allPages.length}`);
